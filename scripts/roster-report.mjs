// Roster report — numbers computed from the ACTUAL loaded roster (src/sim/content.ts through Vite's
// SSR loader, so the TypeScript is the source of truth, never a re-implementation).
//
//   node scripts/roster-report.mjs pareto    regenerate docs/PARETO.md
//   node scripts/roster-report.mjs catalog   refresh the roster marks (★ = active) and the `Serving —` line of
//                                            every pool checkpoint in docs/MODEL-CATALOG.md; lists pool
//                                            checkpoints that have no catalog entry yet
//   node scripts/roster-report.mjs table     print the active roster (size, qualityBy, KV, precision, thinking support)

import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'
import { createServer } from 'vite'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const AXES = ['chat', 'general', 'coding', 'reasoning', 'agentic']
const GRID = [1, 2, 4, 8, 16, 32, 64, 128, 256, 512, 1024, 2048, 4096]
const BUCKETS = [
  ['≤4B', 0, 4], ['4–15B', 4, 15], ['15–40B', 15, 40], ['40–120B', 40, 120], ['120–400B', 120, 400], ['400B–1T', 400, 1000], ['>1T', 1000, Infinity],
]
const bucketOf = (p) => BUCKETS.find(([, lo, hi]) => p > lo && p <= hi)?.[0] ?? '≤4B'

async function load() {
  const server = await createServer({ root: ROOT, logLevel: 'silent', server: { middlewareMode: true }, appType: 'custom' })
  try {
    const content = await server.ssrLoadModule('/src/sim/content.ts')
    const calibrate = await server.ssrLoadModule('/src/sim/calibrate.ts')
    const bench = await server.ssrLoadModule('/src/sim/roster.bench.generated.ts')
    return { content, calibrate, bench }
  } finally {
    await server.close()
  }
}

const frontierAt = (pool, size, axis) => pool.reduce((best, m) => (m.paramsTotalB <= size && m.qualityBy[axis] > best ? m.qualityBy[axis] : best), 0)
const dominatedBy = (pool, m) => pool.find((o) => o !== m && o.paramsTotalB <= m.paramsTotalB && AXES.every((a) => o.qualityBy[a] >= m.qualityBy[a]) && AXES.some((a) => o.qualityBy[a] > m.qualityBy[a]))
const size = (m) => (m.paramsTotalB >= 1000 ? `${(m.paramsTotalB / 1000).toFixed(2).replace(/\.?0+$/, '')}T` : `${m.paramsTotalB}B`)
/** A name that already says its size ("Qwen3.5 4B") is not repeated with it. */
const named = (m) => (/\d(\.\d+)?\s*[BT]\b/i.test(m.name) ? m.name : `${m.name} ${size(m)}`)
const q5 = (m) => AXES.map((a) => m.qualityBy[a]).join(' / ')
const kb = (m) => (m.kvBytesPerToken / 1024).toFixed(1)

/** The models that set an axis' frontier as size grows (the record-setters). */
function frontierWalk(pool, axis) {
  const sorted = [...pool].sort((a, b) => a.paramsTotalB - b.paramsTotalB || b.qualityBy[axis] - a.qualityBy[axis])
  const out = []
  let best = 0
  for (const m of sorted) if (m.qualityBy[axis] > best) { best = m.qualityBy[axis]; out.push(m) }
  return out
}

function pareto({ content, calibrate }) {
  const pool = [...content.MODEL_CANDIDATES]
  const active = Object.values(content.MODEL_DEFS)
  const activeIds = new Set(active.map((m) => m.id))
  const tol = calibrate.ROSTER_FRONTIER_TOLERANCE
  const hand = pool.filter((m) => !m.id.startsWith('g_'))
  const gen = pool.length - hand.length
  const lines = []
  const P = (s = '') => lines.push(s)

  P('# Roster Pareto Analysis')
  P()
  P('How the candidate pool spreads across **size** (parameters) and **capability** (the 5 `qualityBy` axes), and the')
  P('**frontier-tolerance gate** that turns it into the active roster.')
  P()
  P(`The pool is every open-weight checkpoint with an architecture record (\`data/model-arch.json\`): **${pool.length} candidates**`)
  P(`(${hand.length} hand-authored in \`src/sim/content.ts\` + ${gen} generated by \`scripts/gen-roster.mjs\`). A`)
  P(`**${Math.round(tol * 100)}% frontier-tolerance gate** (\`withinFrontierTolerance\`, \`src/sim/calibrate.ts\`) keeps **${active.length} active**`)
  P('checkpoints — the ones the player owns and deploys.')
  P()
  P('Every number below is computed from the *actual loaded roster* (`MODEL_CANDIDATES` / `MODEL_DEFS`, calibrated by')
  P('`src/sim/calibrate.ts`) by `node scripts/roster-report.mjs pareto`. A **frontier** is the (minimize size, maximize')
  P('quality) upper envelope: at each size, the best quality attainable on that axis by a model no larger.')
  P()
  P('---')
  P()
  P('## 1. The five capability frontiers')
  P()
  P(`Evaluated on a log₂ size grid (1 → ${GRID[GRID.length - 1]} B) over the full pool:`)
  P('`frontier(size) = max quality over all candidates with paramsTotalB ≤ size`.')
  P()
  P('```mermaid')
  P('xychart-beta')
  P('  title "Five capability frontiers: size vs best attainable quality"')
  P(`  x-axis "model size (B, log2 grid)" [${GRID.join(', ')}]`)
  P('  y-axis "best quality on axis (0-130)" 0 --> 130')
  for (const a of AXES) P(`  line [${GRID.map((g) => frontierAt(pool, g, a)).join(', ')}]`)
  P('```')
  P()
  P('`xychart-beta` has no legend; the five `line` series, in declaration order, are:')
  P()
  P(`| # | axis | ≤1B | ≤32B | ≤${GRID[GRID.length - 1]}B | the models that set the frontier as size grows |`)
  P('|---|------|----:|-----:|------:|----------------------------------------------|')
  AXES.forEach((a, i) => {
    const walk = frontierWalk(pool, a).map((m) => `${named(m)} (${m.qualityBy[a]})`).join(' → ')
    P(`| ${i + 1} | **${a}** | ${frontierAt(pool, 1, a)} | ${frontierAt(pool, 32, a)} | ${frontierAt(pool, GRID[GRID.length - 1], a)} | ${walk} |`)
  })
  P()
  P('---')
  P()
  P('## 2. Per-size-bucket capability ceilings')
  P()
  P('The best quality on each axis **within** each size bucket (all candidates):')
  P()
  P(`| bucket | candidates | active | ${AXES.join(' | ')} |`)
  P(`|--------|-----------:|-------:|${AXES.map(() => '----:').join('|')}|`)
  for (const [name] of BUCKETS) {
    const inB = pool.filter((m) => bucketOf(m.paramsTotalB) === name)
    if (!inB.length) continue
    const best = AXES.map((a) => Math.max(...inB.map((m) => m.qualityBy[a])))
    P(`| ${name} | ${inB.length} | ${inB.filter((m) => activeIds.has(m.id)).length} | ${best.join(' | ')} |`)
  }
  P()
  const ceiling = (name) => AXES.map((a) => Math.max(0, ...pool.filter((m) => bucketOf(m.paramsTotalB) === name).map((m) => m.qualityBy[a])))
  const mid = ceiling('15–40B')
  const large = ceiling('40–120B')
  if (AXES.every((_, i) => mid[i] >= large[i])) {
    P('**Capability compression:** the best 15–40B checkpoint matches or beats the whole 40–120B band on every axis')
    P(`(${AXES.map((a, i) => `${a} ${mid[i]} vs ${large[i]}`).join(', ')}) — stacking parameters in that band buys`)
    P('nothing, and the ceiling moves only with the multi-hundred-billion MoEs. The gate below keeps only the')
    P('checkpoints that are still a rational pick at their size.')
  } else {
    P('The gate below keeps only the checkpoints that are still a rational pick at their size.')
  }
  P()
  P('---')
  P()
  P(`## 3. The active roster — the ${Math.round(tol * 100)}% frontier-tolerance gate`)
  P()
  P(`A checkpoint stays iff, **on at least one capability axis, its quality is within ${Math.round(tol * 100)}% of the frontier at`)
  P(`its size** (\`ROSTER_FRONTIER_TOLERANCE = ${tol}\`). A model is dropped only when it trails the frontier by more than`)
  P(`${Math.round(tol * 100)}% on every axis — strictly beaten by something no bigger, on all five lanes. The gate trims **${pool.length}`)
  P(`candidates → ${active.length} active**, spanning ${size(active.reduce((a, b) => (b.paramsTotalB < a.paramsTotalB ? b : a)))} → ${size(active.reduce((a, b) => (b.paramsTotalB > a.paramsTotalB ? b : a)))}. The default starter`)
  P(`(\`DEFAULT_MODEL_ID\`) is the smallest dense active model that serves the opening waves on its own — it answers chat`)
  P(`and code completion without thinking and, after its alignment tax, clears the opening quality lines: **${content.MODEL_DEFS[content.DEFAULT_MODEL_ID].name}**.`)
  P('The quality columns are thinking-mode capability; *thinking* names the support the chat template allows')
  P('(`data/model-thinking.json`) with the hidden tokens per thinking-mode answer — a **hybrid** answers chat and code')
  P('completion with thinking off, on its separate thinking-off vector (see MODEL-CATALOG.md).')
  P()
  P('| model | size (total / active) | chat / general / coding / reasoning / agentic | attention | KV per token (+ per request) | release precision | thinking |')
  P('|-------|----------------------|-----------------------------------------------|-----------|------------------------------|-------------------|---------:|')
  for (const m of [...active].sort((a, b) => a.paramsTotalB - b.paramsTotalB)) {
    P(`| ${m.name} | ${size(m)} / ${m.paramsActiveB}B | ${q5(m)} | ${m.attn} | ${kb(m)} KB (+${m.kvStateMbPerReq.toFixed(0)} MB) | ${m.real?.precision ?? '—'} (${m.nativeWeightBytes} B/param) | ${m.thinking === 'never' ? '—' : `${m.thinking} ${m.thinkTokens}`} |`)
  }
  P()
  const pruned = pool.filter((m) => !activeIds.has(m.id)).sort((a, b) => a.paramsTotalB - b.paramsTotalB)
  P(`**Pruned (${pruned.length})** — each trails a no-larger model by more than ${Math.round(tol * 100)}% on every axis:`)
  P(pruned.map((m) => `${m.name} (${size(m)})`).join(' · ') + '.')
  P()
  P('---')
  P()
  P('## 4. Hand-authored entries vs the frontier')
  P()
  P('The hand-authored entries carry the roster\'s identity (recognizable lines, lineage edges, the teaching foils).')
  P('Measured against the full pool:')
  P()
  P('| model | size | on frontier (within the gate) | Pareto-optimal | active |')
  P('|-------|-----:|-------------------------------|:--------------:|:------:|')
  for (const m of [...hand].sort((a, b) => a.paramsTotalB - b.paramsTotalB)) {
    const near = AXES.filter((a) => m.qualityBy[a] >= (1 - tol) * frontierAt(pool, m.paramsTotalB, a))
    const dom = dominatedBy(pool, m)
    P(`| ${m.name} | ${size(m)} | ${near.join(', ') || '—'} | ${dom ? `✗ (${dom.name})` : '✓'} | ${activeIds.has(m.id) ? '✓' : '—'} |`)
  }
  P()
  P('A dominated hand-authored entry is dominated *for real*: the cells are Artificial Analysis measurements on one')
  P('reference scale (bridged only where AA stopped publishing an eval; see `scripts/aa-cells.mjs`), so the')
  P('2024 → 2026 obsolescence the gate prunes is the same capability compression the campaign is built around.')
  P('See [REALISM-MODELS.md](REALISM-MODELS.md) for the build pipeline and [MODEL-CATALOG.md](MODEL-CATALOG.md) for the')
  P('fact-checked roster reference.')
  writeFileSync(join(ROOT, 'docs', 'PARETO.md'), lines.join('\n') + '\n')
  console.log(`✓ wrote docs/PARETO.md — ${pool.length} candidates → ${active.length} active (tolerance ${tol})`)
}

/** The six canonical cells in catalog order (the same labels `aa-sync.mjs catalog` writes). */
const CELLS = [['gpqaDiamond', 'GPQA-D'], ['ifBench', 'IFBench'], ['lcr', 'LCR'], ['sciCode', 'SciCode'], ['terminalBenchHard', 'TB-Hard'], ['hle', 'HLE']]
const GEN_START = '<!-- generated:pool — `node scripts/roster-report.mjs catalog` -->'
const GEN_END = '<!-- /generated:pool -->'

/** A catalog entry composed from the loaded roster (for a pool checkpoint without a hand-written one). */
function generatedEntry(m, nameOf) {
  const size = m.isMoE ? `${m.paramsTotalB}B total / ${m.paramsActiveB}B active (MoE)` : `${m.paramsTotalB}B dense`
  const lineage = m.real?.baseModelId ? `derived from ${nameOf(m.real.baseModelId)}` : '—'
  return [
    `### ${m.name}`,
    `**${m.real?.developer}** · ${(m.real?.released ?? '').slice(0, 7)} · ${m.real?.license} · ${size}${m.thinking === 'hybrid' ? ' · hybrid reasoning' : m.isReasoning ? ' · reasoning' : ''} · ${m.contextWindowK}K ctx · spec: ${m.spec} · lineage: ${lineage} · confidence: ${m.real?.confidence}`,
    `[model card](${m.real?.source})`,
    `Benchmarks — ${CELLS.map(([f, label]) => {
      const v = m.real?.benchmarks?.[f]
      if (v == null) return `${label} —`
      return m.real?.benchmarkSource?.[f]?.startsWith('bridge') ? `${label} ≈${Math.round(v * 10) / 10} (bridged)` : `${label} ${Math.round(v * 10) / 10}`
    }).join(' · ')}  `,
    '',
    m.desc,
    '',
  ].join('\n')
}

/**
 * The thinking support a roster entry is served with (data/model-thinking.json): a hybrid's switch
 * and its thinking-off vector (chat / general / coding / reasoning / agentic), an always-thinker's
 * budget, or none.
 */
function thinkingText(m) {
  const knob = m.real?.thinkingToggle
  const toggle = !knob ? '' : knob === 'none' ? ' (no off switch)' : ` (${knob})`
  if (m.thinking === 'hybrid') {
    const via = m.real?.instantVia ? `AA ${m.real.instantVia}` : 'the thinking→instant pair fit'
    return `hybrid thinking${toggle}: instant on interactive traffic, judged ${AXES.map((a) => m.qualityByInstant[a]).join(' / ')} (from ${via}); thinks ~${m.thinkTokens} hidden tokens elsewhere`
  }
  if (m.thinking === 'always') return `always thinks${toggle}: ~${m.thinkTokens} hidden tokens per answer`
  return 'answers without hidden reasoning'
}

/** Refresh ★ (active in the game) and the `Serving —` architecture line of every catalog entry in the pool. */
function catalog({ content, bench }) {
  const path = join(ROOT, 'docs', 'MODEL-CATALOG.md')
  const map = JSON.parse(readFileSync(join(ROOT, 'data', 'roster-aa-map.json'), 'utf8'))
  const norm = (x) => x.toLowerCase().replace(/[^a-z0-9]/g, '')
  // pass 1: the hand-written entries (everything outside the generated block) and the pool they cover
  let md = readFileSync(path, 'utf8')
  const gs = md.indexOf(GEN_START)
  if (gs >= 0) md = md.slice(0, gs).trimEnd() + '\n'
  const byName = new Map()
  for (const m of content.MODEL_CANDIDATES) {
    for (const n of [map.catalogAliases?.[m.id], m.name, bench.AA_META[m.id]?.name, bench.AA_META[m.id]?.name.replace(/\s*\([^)]*\)\s*$/, '')]) {
      if (n && !byName.has(norm(n))) byName.set(norm(n), m)
    }
  }
  const handHeaders = new Set([...md.matchAll(/^### (.+?)\s*★?\s*$/gm)].map((h) => byName.get(norm(h[1].trim()))?.id).filter(Boolean))
  const missing = content.MODEL_CANDIDATES.filter((m) => !handHeaders.has(m.id)).sort((a, b) => a.paramsTotalB - b.paramsTotalB)
  md +=
    `\n${GEN_START}\n\n## Generated pool entries — ${missing.length} models\n\n` +
    'Pool checkpoints that have no hand-written entry yet, composed from the loaded roster (architecture from each\n' +
    "model's config.json via `data/model-arch.json`, benchmarks from Artificial Analysis). Promote one to a hand-written,\n" +
    'fact-checked entry by moving it into its size section above.\n\n' +
    missing.map((m) => generatedEntry(m, (id) => content.MODEL_CANDIDATES.find((c) => c.id === id)?.name ?? id)).join('\n') +
    `\n${GEN_END}\n`
  // pass 2: marks + serving lines over every entry
  const lines = md.split('\n')
  const out = []
  const seen = new Set()
  let cur = null
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i]
    const h = line.match(/^### (.+?)\s*★?\s*$/)
    if (h) {
      cur = byName.get(norm(h[1].trim())) ?? null
      if (cur) seen.add(cur.id)
      out.push(`### ${h[1].trim()}${cur && content.MODEL_DEFS[cur.id] ? ' ★' : ''}`)
      continue
    }
    if (line.startsWith('Serving —')) continue // regenerated below
    out.push(line)
    if (cur && line.startsWith('Benchmarks')) {
      const m = cur
      const thinks = thinkingText(m)
      out.push(
        `Serving — ${m.attn} · KV ${(m.kvBytesPerToken / 1024).toFixed(1)} KB/token on ${m.kvLayers} of ${m.layers} layers` +
          `${m.kvStateMbPerReq >= 1 ? ` + ${m.kvStateMbPerReq.toFixed(0)} MB/request` : ''} · ${m.real?.precision} weights (${m.nativeWeightBytes} B/param) · ${thinks}  `,
      )
    }
  }
  writeFileSync(path, out.join('\n'))
  const unmatched = content.MODEL_CANDIDATES.filter((m) => !seen.has(m.id))
  console.log(`✓ updated ${path} — ${seen.size} pool checkpoints (${missing.length} in the generated block); ★ on ${[...seen].filter((id) => content.MODEL_DEFS[id]).length}`)
  if (unmatched.length) throw new Error(`pool checkpoints the catalog could not match: ${unmatched.map((m) => m.id).join(', ')}`)
}

function table({ content }) {
  const active = Object.values(content.MODEL_DEFS).sort((a, b) => a.paramsTotalB - b.paramsTotalB)
  for (const m of active) {
    const inst = m.qualityByInstant ? `  instant ${AXES.map((a) => m.qualityByInstant[a]).join(' / ')}` : ''
    console.log(`${m.id.padEnd(32)} ${size(m).padStart(6)}/${String(m.paramsActiveB).padEnd(5)} ${q5(m).padEnd(26)} ${m.attn.padEnd(13)} KV ${kb(m).padStart(6)} KB +${m.kvStateMbPerReq.toFixed(0).padStart(4)} MB  ${String(m.real?.precision).padEnd(5)} ${m.nativeWeightBytes} B/p  ${m.thinking.padEnd(6)} think ${m.thinkTokens}${inst}`)
  }
  console.log(`${active.length} active · default ${content.DEFAULT_MODEL_ID}`)
}

const cmd = process.argv[2]
const mods = await load()
if (cmd === 'pareto') pareto(mods)
else if (cmd === 'catalog') catalog(mods)
else if (cmd === 'table') table(mods)
else { console.error('usage: node scripts/roster-report.mjs <pareto|catalog|table>'); process.exit(1) }
